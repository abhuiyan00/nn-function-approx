import { useQueries, useQuery } from "@tanstack/react-query";
import { ArrowLeft, Play } from "lucide-react";
import { useState } from "react";
import { Link, useParams } from "react-router";
import { RunsChart } from "@/components/charts/RunsChart";
import { DataTable } from "@/components/DataTable";
import { EmptyState, ErrorState, LoadingBlock, Notice, PageHeader, ProfileBadge, Section, Segmented } from "@/components/common";
import { Markdown } from "@/components/Markdown";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Dialog, DialogContent, DialogDescription, DialogTitle } from "@/components/ui/dialog";
import { type Dataset, api } from "@/lib/api";
import { EXPERIMENT_CHARTS } from "@/lib/experimentCharts";

function Figures({ figures, id }: { figures: { name: string; url: string }[]; id: string }) {
  const [open, setOpen] = useState<{ name: string; url: string } | null>(null);
  return (
    <>
      <ul className="grid grid-cols-1 gap-3 md:grid-cols-2">
        {figures.map((f) => (
          <li key={f.url}>
            <button type="button" onClick={() => setOpen(f)} className="group block w-full overflow-hidden rounded-lg border bg-white text-left transition-colors hover:border-axis" aria-label={`Enlarge figure: ${f.name}`}>
              <img src={f.url} alt={`${id.toUpperCase()} figure: ${f.name}`} loading="lazy" className="h-56 w-full object-contain p-2" />
              <span className="block border-t bg-card px-3 py-1.5 text-xs text-muted-foreground capitalize">{f.name}</span>
            </button>
          </li>
        ))}
      </ul>
      <Dialog open={!!open} onOpenChange={(v) => !v && setOpen(null)}>
        <DialogContent className="max-h-[92dvh] max-w-[min(1200px,94vw)] overflow-auto sm:max-w-[min(1200px,94vw)]">
          <DialogTitle className="capitalize">{open?.name}</DialogTitle>
          <DialogDescription className="sr-only">Figure generated by the experiment script</DialogDescription>
          {open && <img src={open.url} alt={`${id.toUpperCase()} figure: ${open.name}`} className="w-full rounded-md bg-white" />}
        </DialogContent>
      </Dialog>
    </>
  );
}

function RawData({ datasets, exp }: { datasets: Dataset[]; exp: string }) {
  const [name, setName] = useState(datasets[0]?.name);
  const data = datasets.find((d) => d.name === name) ?? datasets[0];
  if (!data) return null;
  return (
    <div className="space-y-2">
      {datasets.length > 1 && <Segmented label="Result file" value={data.name} onChange={setName} options={datasets.map((d) => ({ value: d.name, label: d.name }))} />}
      <DataTable columns={data.columns} rows={data.rows} filename={`${exp}_${data.name}`} />
    </div>
  );
}

export function ExperimentDetail() {
  const { id = "" } = useParams();
  const detail = useQuery({ queryKey: ["experiment", id], queryFn: () => api.experiment(id) });
  const names = detail.data?.datasets.map((d) => d.name) ?? [];
  const results = useQueries({
    queries: names.map((name) => ({ queryKey: ["dataset", id, name], queryFn: () => api.dataset(id, name) })),
  });

  if (detail.isError) {
    return (
      <EmptyState title="Unknown experiment" action={<Button variant="outline" asChild><Link to="/experiments">All experiments</Link></Button>}>
        There is no experiment called {id}.
      </EmptyState>
    );
  }
  if (!detail.data) return <LoadingBlock className="h-[600px]" />;
  const e = detail.data;
  const datasets = results.map((r) => r.data).filter((d): d is Dataset => !!d);
  const failed = results.find((r) => r.isError);
  const charts = EXPERIMENT_CHARTS[id] ?? [];

  return (
    <div className="space-y-6">
      <div>
        <Button variant="link" size="sm" asChild className="-ml-3 text-muted-foreground">
          <Link to="/experiments"><ArrowLeft /> All experiments</Link>
        </Button>
        <PageHeader
          title={`${e.id.toUpperCase()} · ${e.title}`}
          description={e.question}
          actions={
            <>
              <ProfileBadge profile={e.profile} />
              <Button variant="outline" size="sm" asChild><Link to={`/runner?experiment=${e.id}`}><Play /> Run again</Link></Button>
            </>
          }
        />
        <p className="mt-1 text-xs text-subtle">
          {e.generated ? `Generated ${e.generated}` : "No results yet"}{e.owner ? ` · Owner: Member ${e.owner}` : ""} · Script: experiments/{e.script}.py
        </p>
      </div>

      {e.profile === "quick" && (
        <Notice tone="warning">Quick-profile numbers: the full profile must confirm them before the report. Effects below about ×1.5 are within seed spread.</Notice>
      )}

      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Card className="gap-2 p-4">
          <h2 className="text-sm font-semibold">What we expected</h2>
          <p className="text-[13px] leading-relaxed">{e.hypothesis}</p>
          <h3 className="mt-2 text-xs font-semibold text-muted-foreground">Protocol</h3>
          <Markdown className="text-[13px]">{e.protocol}</Markdown>
        </Card>
        <Card className="gap-2 p-4">
          <h2 className="text-sm font-semibold">What we found</h2>
          {e.findings ? <Markdown className="text-[13px]">{e.findings}</Markdown> : <p className="text-[13px] text-muted-foreground">Not written up yet in docs/FINDINGS.md.</p>}
        </Card>
      </div>

      {failed && <ErrorState error={failed.error} onRetry={() => failed.refetch()} />}
      {charts.length > 0 && (
        <Section title="Interactive results" description="Drawn from the result files. Hover or use the arrow keys for values; the table icon shows the same numbers as text.">
          <div className={`grid grid-cols-1 gap-4 ${charts.length > 1 ? "xl:grid-cols-2" : ""}`}>
            {charts.map((spec) => {
              const data = datasets.find((d) => d.name === spec.dataset);
              return data ? <RunsChart key={spec.id} spec={spec} data={data} /> : <LoadingBlock key={spec.id} />;
            })}
          </div>
        </Section>
      )}

      {e.summary && (
        <Section title="Summary tables" description="Written by the experiment script.">
          <Card className="p-4"><Markdown className="text-[13px]">{e.summary}</Markdown></Card>
        </Section>
      )}

      {e.figures.length > 0 && (
        <Section title="Report figures" description="As generated for the report. Select one to enlarge it.">
          <Figures figures={e.figures} id={e.id} />
        </Section>
      )}

      {datasets.length > 0 && (
        <Section title="Raw data" description="Every run with its full settings.">
          <RawData datasets={datasets} exp={e.id} />
        </Section>
      )}
    </div>
  );
}
