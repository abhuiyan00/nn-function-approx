"""Run every experiment and collect the summaries into docs/RESULTS.md.

    python experiments/run_all.py --profile quick        (~20 min on 2 cores)
    python experiments/run_all.py --profile full         (hours - run overnight)
    python experiments/run_all.py --only e1 u2           (subset, by prefix)
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["e0_sanity", "e1_architecture", "e2_activation_init", "e3_training", "e4_data_noise",
         "e5_regularisation", "e6_baselines", "u1_levenberg_marquardt", "u2_kan_vs_mlp",
         "u3_spectral_bias", "u4_uncertainty"]

HEADER = """# Results

Auto-generated by `experiments/run_all.py` from `results/<experiment>/summary.md`.
Figures are in `docs/figures/`, raw per-run rows in `results/<experiment>/*.csv`.
All errors are measured against the **exact** target on a dense grid (10,000 points),
not against noisy labels, unless a column says otherwise.

"""


def collect() -> Path:
    parts = [HEADER]
    for name in ORDER:
        s = ROOT / "results" / name / "summary.md"
        if s.exists():
            parts.append(s.read_text(encoding="utf-8").strip() + "\n")
            figs = sorted((ROOT / "docs" / "figures").glob(f"{name}_*.png"))
            parts.append("\n".join(f"![{p.stem}](figures/{p.name})" for p in figs) + "\n")
    out = ROOT / "docs" / "RESULTS.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--profile", default="quick", choices=["quick", "full"])
    p.add_argument("--only", nargs="*", default=None)
    p.add_argument("--collect-only", action="store_true")
    a = p.parse_args()
    if not a.collect_only:
        todo = [n for n in ORDER if not a.only or any(n.startswith(o) for o in a.only)]
        t0 = time.time()
        for name in todo:
            print(f"[{time.time() - t0:6.0f} s] {name}", flush=True)
            r = subprocess.run([sys.executable, str(ROOT / "experiments" / f"{name}.py"), "--profile", a.profile],
                               cwd=ROOT / "experiments")
            if r.returncode:
                print(f"  FAILED: {name} (exit {r.returncode})")
        print(f"done in {time.time() - t0:.0f} s")
    print(f"wrote {collect().relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
